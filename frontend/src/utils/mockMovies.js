// Unified catalog array with duplicates removed
export const allMockMovies = (() => {
  const map = new Map();
  [featuredMovie, ...trendingMovies, ...popularMovies, ...topRatedMovies].forEach((m) => {
    if (m && m.id && !map.has(m.id)) {
      map.set(m.id, m);
    }
  });
  return Array.from(map.values());
})();

/**
 * Find a movie by its ID or return null
 */
export const getMovieById = (id) => {
  if (!id) return null;
  return allMockMovies.find((m) => m.id === id || m.movieId === id) || null;
};

